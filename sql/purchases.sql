-- Standalone purchase setup; do not apply the conflicted sql/schema.sql.
-- Preserve the actual ID types of the referenced tables (int4 or int8).
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
DO $$
DECLARE
  listing_id_type text;
  user_id_type text;
  bid_id_type text;
BEGIN
  SELECT format_type(atttypid, atttypmod) INTO listing_id_type FROM pg_attribute
    WHERE attrelid = 'public.listings'::regclass AND attname = 'id';
  SELECT format_type(atttypid, atttypmod) INTO user_id_type FROM pg_attribute
    WHERE attrelid = 'public.users'::regclass AND attname = 'id';
  SELECT format_type(atttypid, atttypmod) INTO bid_id_type FROM pg_attribute
    WHERE attrelid = 'public.bids'::regclass AND attname = 'id';
  EXECUTE format(
    'CREATE TABLE IF NOT EXISTS public.purchases (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      listing_id %s NOT NULL REFERENCES public.listings(id),
      buyer_id %s NOT NULL REFERENCES public.users(id),
      seller_id %s NOT NULL REFERENCES public.users(id),
      winning_bid_id %s REFERENCES public.bids(id),
      amount_cents integer NOT NULL CHECK (amount_cents > 0),
      created_at timestamptz NOT NULL DEFAULT now(),
      CHECK (buyer_id <> seller_id)
    )', listing_id_type, user_id_type, user_id_type, bid_id_type);
END $$;

-- Fail safely if historical duplicates exist; never delete existing purchases.
CREATE UNIQUE INDEX IF NOT EXISTS purchases_one_per_listing_idx ON public.purchases (listing_id);
CREATE INDEX IF NOT EXISTS purchases_buyer_history_idx ON public.purchases (buyer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS purchases_seller_history_idx ON public.purchases (seller_id, created_at DESC);
ALTER TABLE public.purchases ENABLE ROW LEVEL SECURITY;
-- Express uses its trusted database connection; browser Data API access stays blocked.
COMMIT;
